CREATE TABLE incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL REFERENCES project_repositories(id) ON DELETE RESTRICT,
    fingerprint VARCHAR(64) NOT NULL,
    severity VARCHAR(10) NOT NULL,
    status VARCHAR(20) NOT NULL,
    review_reason VARCHAR(1000),
    last_actor_type VARCHAR(20),
    last_actor_reference BIGINT,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT incidents_repository_fingerprint_uk UNIQUE (repository_id, fingerprint),
    CONSTRAINT incidents_fingerprint_format CHECK (fingerprint ~ '^[0-9a-f]{64}$'),
    CONSTRAINT incidents_severity_allowed CHECK (severity IN ('CRITICAL','HIGH','MEDIUM','LOW','INFO')),
    CONSTRAINT incidents_status_allowed CHECK (status IN ('OPEN','RESOLVED','IGNORED')),
    CONSTRAINT incidents_actor_allowed CHECK (
        (last_actor_type IS NULL AND last_actor_reference IS NULL)
        OR (last_actor_type = 'SYSTEM' AND last_actor_reference IS NULL)
        OR (last_actor_type IN ('USER','MACHINE') AND last_actor_reference IS NOT NULL)
    )
);

ALTER TABLE findings ADD COLUMN incident_id BIGINT REFERENCES incidents(id) ON DELETE RESTRICT;

CREATE INDEX incidents_repository_created_idx
    ON incidents(repository_id, created_at DESC, id DESC);
CREATE INDEX incidents_repository_status_idx
    ON incidents(repository_id, status, severity);
CREATE INDEX findings_incident_idx ON findings(incident_id, created_at DESC, id DESC);

CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL REFERENCES project_repositories(id) ON DELETE RESTRICT,
    actor_type VARCHAR(20) NOT NULL,
    actor_user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    actor_credential_id BIGINT REFERENCES ci_credentials(id) ON DELETE RESTRICT,
    operation VARCHAR(64) NOT NULL,
    target_type VARCHAR(32) NOT NULL,
    target_id BIGINT NOT NULL,
    safe_change_summary VARCHAR(500) NOT NULL,
    occurred_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT audit_events_actor_allowed CHECK (
        (actor_type = 'USER' AND actor_user_id IS NOT NULL AND actor_credential_id IS NULL)
        OR (actor_type = 'MACHINE' AND actor_user_id IS NULL AND actor_credential_id IS NOT NULL)
        OR (actor_type = 'SYSTEM' AND actor_user_id IS NULL AND actor_credential_id IS NULL)
    ),
    CONSTRAINT audit_events_operation_allowed CHECK (operation IN (
        'REPOSITORY_CREATED','REPOSITORY_UPDATED','REPOSITORY_DEACTIVATED',
        'SCAN_CREATED','SCAN_STARTED','SCAN_COMPLETED','SCAN_FAILED',
        'INCIDENT_CREATED','INCIDENT_RESOLVED','INCIDENT_IGNORED','INCIDENT_REOPENED',
        'CI_CREDENTIAL_CREATED','CI_CREDENTIAL_REVOKED'
    )),
    CONSTRAINT audit_events_target_allowed CHECK (
        target_type IN ('REPOSITORY','SCAN','FINDING','INCIDENT','CI_CREDENTIAL')
    )
);

CREATE INDEX audit_events_repository_occurred_idx
    ON audit_events(repository_id, occurred_at DESC, id DESC);
CREATE INDEX audit_events_repository_operation_idx
    ON audit_events(repository_id, operation, actor_type);

-- Preserve findings imported before incident management existed. Their first
-- occurrence determines the incident creation time; severity is the highest
-- observed severity for that repository/fingerprint identity.
INSERT INTO incidents (repository_id, fingerprint, severity, status,
        last_actor_type, version, created_at, updated_at)
SELECT scan.repository_id, finding.fingerprint,
       CASE MIN(CASE finding.severity
           WHEN 'CRITICAL' THEN 0 WHEN 'HIGH' THEN 1 WHEN 'MEDIUM' THEN 2
           WHEN 'LOW' THEN 3 ELSE 4 END)
           WHEN 0 THEN 'CRITICAL' WHEN 1 THEN 'HIGH' WHEN 2 THEN 'MEDIUM'
           WHEN 3 THEN 'LOW' ELSE 'INFO' END,
       'OPEN', 'SYSTEM', 0, MIN(finding.created_at), MAX(finding.created_at)
FROM findings finding
JOIN scans scan ON scan.id = finding.scan_id
GROUP BY scan.repository_id, finding.fingerprint;

UPDATE findings finding
SET incident_id = incident.id
FROM scans scan, incidents incident
WHERE scan.id = finding.scan_id
  AND incident.repository_id = scan.repository_id
  AND incident.fingerprint = finding.fingerprint;

ALTER TABLE findings ALTER COLUMN incident_id SET NOT NULL;

INSERT INTO audit_events (repository_id, actor_type, operation, target_type,
        target_id, safe_change_summary, occurred_at)
SELECT repository_id, 'SYSTEM', 'INCIDENT_CREATED', 'INCIDENT', id,
       'Incident opened from historical finding migration',
       CURRENT_TIMESTAMP AT TIME ZONE 'UTC'
FROM incidents;
