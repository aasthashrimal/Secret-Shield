CREATE TABLE project_repositories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    github_owner VARCHAR(39) NOT NULL,
    github_name VARCHAR(100) NOT NULL,
    canonical_url VARCHAR(255) NOT NULL,
    default_branch VARCHAR(255) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT project_repositories_owner_fk FOREIGN KEY (owner_id)
        REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT project_repositories_owner_identity_uk
        UNIQUE (owner_id, github_owner, github_name),
    CONSTRAINT project_repositories_github_owner_lowercase
        CHECK (github_owner = lower(github_owner)),
    CONSTRAINT project_repositories_github_name_lowercase
        CHECK (github_name = lower(github_name)),
    CONSTRAINT project_repositories_canonical_url
        CHECK (canonical_url = 'https://github.com/' || github_owner || '/' || github_name),
    CONSTRAINT project_repositories_default_branch_nonblank
        CHECK (length(btrim(default_branch)) BETWEEN 1 AND 255)
);

CREATE INDEX project_repositories_owner_created_idx
    ON project_repositories (owner_id, created_at DESC, id DESC);
CREATE INDEX project_repositories_created_idx
    ON project_repositories (created_at DESC, id DESC);
