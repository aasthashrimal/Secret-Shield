CREATE TABLE scans (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 repository_id BIGINT NOT NULL REFERENCES project_repositories(id) ON DELETE RESTRICT,
 commit_sha VARCHAR(40) NOT NULL,
 branch VARCHAR(255) NOT NULL,
 trigger VARCHAR(20) NOT NULL,
 run_id VARCHAR(200), run_attempt INTEGER, scanner_version VARCHAR(100),
 status VARCHAR(30) NOT NULL, failure_code VARCHAR(64), payload_digest VARCHAR(64),
 started_at TIMESTAMP(6), completed_at TIMESTAMP(6),
 created_at TIMESTAMP(6) NOT NULL, updated_at TIMESTAMP(6) NOT NULL,
 CONSTRAINT scans_trigger_allowed CHECK (trigger IN ('MANUAL','CI_PUSH','CI_PR')),
 CONSTRAINT scans_status_allowed CHECK (status IN ('QUEUED','RUNNING','CLEAN','FINDINGS_DETECTED','FAILED')),
 CONSTRAINT scans_commit_sha CHECK (commit_sha ~ '^[0-9a-f]{40}$'),
 CONSTRAINT scans_ci_identity CHECK ((trigger='MANUAL' AND run_id IS NULL AND run_attempt IS NULL) OR
   (trigger IN ('CI_PUSH','CI_PR') AND run_id IS NOT NULL AND run_attempt > 0))
);
CREATE UNIQUE INDEX scans_ci_identity_uk ON scans(repository_id,run_id,run_attempt,commit_sha)
 WHERE run_id IS NOT NULL;
CREATE INDEX scans_repository_created_idx ON scans(repository_id,created_at DESC,id DESC);

CREATE TABLE ci_credentials (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 repository_id BIGINT NOT NULL REFERENCES project_repositories(id) ON DELETE RESTRICT,
 secret_hash VARCHAR(100) NOT NULL,
 created_at TIMESTAMP(6) NOT NULL,
 expires_at TIMESTAMP(6), revoked_at TIMESTAMP(6),
 CONSTRAINT ci_credentials_expiry CHECK (expires_at IS NULL OR expires_at > created_at)
);
CREATE INDEX ci_credentials_repository_idx ON ci_credentials(repository_id,id DESC);
