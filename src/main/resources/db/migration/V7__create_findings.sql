CREATE TABLE findings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id BIGINT NOT NULL REFERENCES scans(id) ON DELETE RESTRICT,
    fingerprint VARCHAR(64) NOT NULL,
    rule_id VARCHAR(200) NOT NULL,
    severity VARCHAR(10) NOT NULL,
    file_path VARCHAR(1000) NOT NULL,
    line INTEGER NOT NULL,
    commit_sha VARCHAR(40) NOT NULL,
    sanitized_description VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT findings_scan_fingerprint_uk UNIQUE (scan_id, fingerprint),
    CONSTRAINT findings_fingerprint_format CHECK (fingerprint ~ '^[0-9a-f]{64}$'),
    CONSTRAINT findings_commit_sha_format CHECK (commit_sha ~ '^[0-9a-f]{40}$'),
    CONSTRAINT findings_line_positive CHECK (line > 0),
    CONSTRAINT findings_severity_allowed CHECK (severity IN ('CRITICAL','HIGH','MEDIUM','LOW','INFO'))
);

CREATE INDEX findings_scan_created_idx ON findings(scan_id, created_at DESC, id DESC);
CREATE INDEX findings_severity_rule_idx ON findings(severity, rule_id);
