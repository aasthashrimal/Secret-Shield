ALTER TABLE audit_events DROP CONSTRAINT audit_events_operation_allowed;
ALTER TABLE audit_events ADD CONSTRAINT audit_events_operation_allowed CHECK (operation IN (
    'REPOSITORY_CREATED','REPOSITORY_UPDATED','REPOSITORY_DEACTIVATED',
    'SCAN_CREATED','SCAN_STARTED','SCAN_COMPLETED','SCAN_FAILED',
    'INCIDENT_CREATED','INCIDENT_RESOLVED','INCIDENT_IGNORED','INCIDENT_REOPENED',
    'INCIDENT_OCCURRENCE','CI_CREDENTIAL_CREATED','CI_CREDENTIAL_REVOKED'
));

CREATE TABLE notification_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incidents(id) ON DELETE RESTRICT,
    audit_event_id BIGINT NOT NULL REFERENCES audit_events(id) ON DELETE RESTRICT,
    recipient_config_reference VARCHAR(32) NOT NULL,
    status VARCHAR(12) NOT NULL,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    safe_error_code VARCHAR(64),
    next_attempt_at TIMESTAMP(6) NOT NULL,
    lease_until TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT notification_event_recipient_uk UNIQUE (audit_event_id, recipient_config_reference),
    CONSTRAINT notification_status_allowed CHECK (status IN ('QUEUED','SENDING','SENT','FAILED')),
    CONSTRAINT notification_attempt_bounds CHECK (attempt_count BETWEEN 0 AND 3),
    CONSTRAINT notification_recipient_reference_format CHECK (
        recipient_config_reference ~ '^[a-z][a-z0-9_-]{0,31}$'),
    CONSTRAINT notification_status_consistency CHECK (
        (status = 'QUEUED' AND attempt_count = 0 AND safe_error_code IS NULL AND lease_until IS NULL)
        OR (status = 'SENDING' AND attempt_count BETWEEN 1 AND 3 AND lease_until IS NOT NULL)
        OR (status = 'SENT' AND attempt_count BETWEEN 1 AND 3 AND safe_error_code IS NULL AND lease_until IS NULL)
        OR (status = 'FAILED' AND attempt_count BETWEEN 1 AND 3 AND safe_error_code IS NOT NULL AND lease_until IS NULL)
    )
);

CREATE INDEX notification_due_idx ON notification_deliveries(status, next_attempt_at, id);
CREATE INDEX notification_incident_created_idx
    ON notification_deliveries(incident_id, created_at DESC, id DESC);
